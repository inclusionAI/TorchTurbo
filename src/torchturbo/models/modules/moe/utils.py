@dataclass(frozen=True, slots=True)
class RoutingResult:
    """Route assignments and weights for one local token batch.

    Attributes:
        probs: Final dense routing weights, shaped [tokens, experts].
        routing_map: Boolean assignment mask, shaped [tokens, experts].
        expert_indices: Selected IDs sorted per token, shaped [tokens, top_k].
    """

    probs: torch.Tensor
    routing_map: torch.Tensor
    expert_indices: torch.Tensor

    def selected_probs(self) -> torch.Tensor:
        """Gather final weights in the exact order used for permutation."""
        return self.probs.gather(1, self.expert_indices)


def slice_tensor_for_ep_rank(tensor, ep_rank, ep_world_size):
    assert ep_world_size > 0, "must be"

    total_dim = tensor.shape[0]
    chunk_size = total_dim // ep_world_size

    start = ep_rank * chunk_size
    end = start + chunk_size

    return tensor[start:end]


def group_limited_topk(
    scores: torch.Tensor,
    topk: int,
    num_tokens: int,
    num_experts: int,
    num_groups: int,
    group_topk: int,
):
    """Perform top-k routing on a subset of expert groups.
    When using group-limited routing:
    1. Experts are divided into 'moe_router_num_groups' equal-sized groups
    2. For each token, 'moe_router_group_topk' groups are selected based on routing scores
       (specifically, the sum of top-2 expert scores within each group)
    3. From these selected groups, 'moe_router_topk' individual experts are chosen
    Two common use cases:
    - Device-limited routing: Set 'moe_router_num_groups' equal to expert parallel size (EP)
      to limit each token to experts on a subset of devices
      (See DeepSeek-V2: https://arxiv.org/pdf/2405.04434)
    - Node-limited routing: Set 'moe_router_num_groups' equal to number of nodes in EP group
      to limit each token to experts on a subset of nodes
      (See DeepSeek-V3: https://arxiv.org/pdf/2412.19437)
    Args:
        scores (torch.Tensor): Softmax scores generated by the router.
        topk (int): The number of experts to select for each token.
        num_tokens (int): The number of tokens.
        num_experts (int): The number of experts.
        num_groups (int): Number of groups for routed experts.
        group_topk (int): Number of groups selected for each token.
    Returns:
        Tuple[torch.Tensor, torch.Tensor]: Probs and indices tensor.
    """
    # Organize the experts into groups
    # Select groups based on sum of top-(topk/group_topk) routing scores within each group
    group_scores = (
        scores.view(num_tokens, num_groups, -1)
        .topk(topk // group_topk, dim=-1)[0]
        .sum(dim=-1)
    )
    group_idx = torch.topk(group_scores, k=group_topk, dim=-1, sorted=False)[1]
    group_mask = torch.zeros_like(group_scores)
    group_mask.scatter_(1, group_idx, 1)

    # Mask the experts based on selection groups
    score_mask = (
        group_mask.unsqueeze(-1)
        .expand(num_tokens, num_groups, num_experts // num_groups)
        .reshape(num_tokens, -1)
    )

    masked_scores = scores.masked_fill(~score_mask.bool(), float("-inf"))
    probs, top_indices = torch.topk(masked_scores, k=topk, dim=-1)

    return probs, top_indices


def get_capacity(
    num_tokens: int, num_experts: int, capacity_factor: float, min_capacity=None
):
    """
    Calculate the capacity of each expert.

    Args:
        num_tokens (int): num of the input tokens.
        num_experts (int): num of the experts.
        capacity_factor (float): Capacity factor.
        min_capacity (int, optional): Minimum capacity. Defaults to None.

    Returns:
        Tensor: Capacity of each expert.
    """
    capacity = math.ceil((num_tokens / num_experts) * capacity_factor)
    if min_capacity is not None and capacity < min_capacity:
        capacity = min_capacity
    return capacity


def permute(
    tokens: torch.Tensor,
    routing_map: torch.Tensor,
    probs: Optional[torch.Tensor] = None,
    num_out_tokens: Optional[int] = None,
    fused: bool = False,
    expert_indices: Optional[torch.Tensor] = None,
) -> tuple[
    torch.Tensor, Optional[torch.Tensor],
    torch.Tensor | tuple[torch.Tensor, torch.Tensor],
]:
    """Permute the tokens and probs based on the mask.
    Tokens with the same designated expert will be grouped together.
    The shape of mask is [tokens, num_experts], it indicates which experts were selected
    by each token.

    Args:
        tokens (torch.Tensor): The input token tensor, [num_tokens, hidden].
        routing_map (torch.Tensor): The sparse token to expert mapping, [num_tokens, num_experts].
        probs (torch.Tensor, optional): Routing probabilities, [num_tokens, num_experts].
        num_out_tokens (int, optional): Required output count for fused permutation.
        fused (bool, optional): Require the device's fused permutation implementation.
        expert_indices (torch.Tensor, optional): Cached expert IDs matching routing_map,
            shaped [num_tokens, topk] and sorted per token.

    Returns:
        tuple: Permuted tokens, optional probabilities, and the inverse mapping.
            The fused mapping must be passed to unpermute with fused=True.
    """
    # Each backend's inverse mapping must stay paired with its unpermutation.
    if fused:
        return ops.moe_fused_permutation(
            tokens, routing_map, probs=probs, num_out_tokens=num_out_tokens,
            expert_indices=expert_indices,
        )
    return ops.moe_mask_permutation(
        tokens, routing_map, probs=probs, num_out_tokens=num_out_tokens,
        expert_indices=expert_indices, impl="torch_moe_mask_permutation",
    )


def sort_chunks_by_idxs(
    input: torch.Tensor,
    split_sizes: torch.Tensor,
    sorted_idxs: torch.Tensor,
    probs: Optional[torch.Tensor] = None,
    fused: bool = False,
) -> tuple[torch.Tensor, Optional[torch.Tensor]]:
    """Split and sort tokens and probabilities by chunk indices.

    Fused sorting requires split_sizes and sorted_idxs on the input device.
    Fused sorting uses the device's implementation without a native fallback.
    """
    if fused:
        return ops.moe_fused_sort_chunks(input, split_sizes, sorted_idxs, probs=probs)
    return ops.moe_sort_chunks(
        input, split_sizes, sorted_idxs, probs=probs,
        impl="torch_moe_sort_chunks",
    )


def unpermute(
    permuted_tokens: torch.Tensor,
    sorted_indices: torch.Tensor | tuple[torch.Tensor, torch.Tensor],
    restore_shape: torch.Size,
    probs: Optional[torch.Tensor] = None,
    routing_map: Optional[torch.Tensor] = None,
    fused: bool = False,
) -> torch.Tensor:
    """
    Restore the original order of tokens after permutation. If probs are provided, it
    will also apply them to the tokens before restoring the order.

    Args:
        permuted_tokens (torch.Tensor): The permuted token tensor.
        sorted_indices: The backend-specific inverse mapping returned by permute.
        restore_shape (torch.Size): The shape of the unpermuted tensor.
        probs (torch.Tensor, optional): The unpermuted probs tensor,
        routing_map (torch.Tensor, optional): Token to expert mapping, shape
            [num_tokens, num_experts].
        fused (bool, optional): Use the matching device implementation for a fused mapping.

    Returns:
        torch.Tensor: The tokens restored to their original order.
    """
    if fused:
        return ops.moe_fused_unpermutation(
            permuted_tokens, sorted_indices, restore_shape,
            probs=probs, routing_map=routing_map,
        )
    return ops.moe_mask_unpermutation(
        permuted_tokens, sorted_indices, restore_shape,
        probs=probs, routing_map=routing_map,
        impl="torch_moe_mask_unpermutation",
    )


def maybe_move_tensor_to_cpu(
    tensor: torch.Tensor | np.ndarray | None,
    as_numpy: bool = False,
    record_stream: bool = False,
) -> torch.Tensor | np.ndarray | None:
    """Move a tensor to CPU and optionally expose it as a numpy array.
    Args:
        tensor (torch.Tensor, np.ndarray or None): Device tensor or existing host metadata.
        as_numpy (bool): Whether to convert the tensor to a numpy array.
        record_stream (bool): Keep device storage alive until the side-stream copy completes.
    """
    if torch.is_tensor(tensor) and tensor.device.type != "cpu":
        cpu_tensor = tensor.to(torch.device("cpu"), non_blocking=True)
        if record_stream:
            current_stream = get_device_runtime().current_stream()
            if current_stream is not None:
                tensor.record_stream(current_stream)
        tensor = cpu_tensor
    if as_numpy and torch.is_tensor(tensor):
        tensor = tensor.numpy()
    return tensor


def topk_softmax_with_capacity(
    logits: torch.Tensor,
    topk: int,
    use_pre_softmax: bool = False,
    num_groups: Optional[int] = None,
    group_topk: Optional[int] = None,
    scaling_factor: Optional[float] = None,
    score_function: str = "softmax",
    expert_bias: Optional[torch.Tensor] = None,
    use_hash_routing: bool = False,
    hash_table: Optional[torch.Tensor] = None,
    input_ids: Optional[torch.Tensor] = None,
    normalize_topk_prob: bool = False,
) -> RoutingResult:
    """Apply capacity and padding to the top-k selection.
    Args:
        logits (torch.Tensor): Logits tensor.
        topk (int): The number of experts to select for each token.
        capacity_factor (float): The capacity factor of each expert. Will drop tokens if the number
                               of tokens exceeds the capacity.
        pad_to_capacity (bool): Whether to need padding in token drop mode. The probs for padded
                               tokens will be 0.
        drop_policy (str): The policy to drop tokens. Can be either "prob" or "position".
                           If "prob", the tokens with the lowest probabilities will be dropped.
                           If "position", tokens at the end of each batch will be dropped.
        use_pre_softmax (bool): Whether to apply softmax or sigmoid before top-k selection.
        num_groups (int): Number of groups for routed experts.
        group_topk (int): Number of selected groups for each token.
        scaling_factor (float): Scaling factor of routing score in top-k selection.
        score_function (str): The score function to use. Can be either "softmax" or "sigmoid".
        expert_bias (torch.Tensor): The bias added to logits for expert routing.
        normalize_topk_prob (bool): Renormalize selected softmax probabilities before scaling.

    Returns:
        RoutingResult: Dense weights and mask, plus selected expert IDs in
        ascending expert-ID order for each token.
    """
    assert (
        logits.dim() == 2
    ), f"Expected 2D logits [num_tokens, num_experts], got {logits.dim()}."
    num_tokens, num_experts = logits.shape

    def compute_topk(scores, topk, num_groups=None, group_topk=None):
        if group_topk:
            return group_limited_topk(
                scores=scores,
                topk=topk,
                num_tokens=num_tokens,
                num_experts=num_experts,
                num_groups=num_groups,
                group_topk=group_topk,
            )
        else:
            return torch.topk(scores, k=topk, dim=1)

    if score_function == "softmax":
        scores = torch.softmax(logits, dim=-1, dtype=torch.float32)
        if use_hash_routing:
            assert (
                hash_table is not None and input_ids is not None
            ), "Hash routing requires hash_table and input_ids."
            top_indices = hash_table[input_ids]
            probs = torch.gather(scores, dim=1, index=top_indices)
        elif use_pre_softmax:
            probs, top_indices = compute_topk(scores, topk, num_groups, group_topk)
        else:
            top_scores, top_indices = compute_topk(logits, topk, num_groups, group_topk)
            probs = torch.softmax(top_scores, dim=-1, dtype=torch.float32)
        if normalize_topk_prob:
            probs = probs / probs.sum(dim=-1, keepdim=True)
    elif score_function in ("sigmoid", "sqrtsoftplus"):
        if score_function == "sigmoid":
            scores = torch.sigmoid(logits.float())
        else:
            scores = torch.nn.functional.softplus(logits.float()).sqrt()

        if use_hash_routing:
            assert (
                hash_table is not None and input_ids is not None
            ), "Hash routing requires hash_table and input_ids."
            top_indices = hash_table[input_ids]
            scores = torch.gather(scores, dim=1, index=top_indices)
        elif expert_bias is not None:
            scores_for_routing = scores + expert_bias.float()
            _, top_indices = compute_topk(
                scores_for_routing, topk, num_groups, group_topk
            )
            scores = torch.gather(scores, dim=1, index=top_indices)
        else:
            scores, top_indices = compute_topk(scores, topk, num_groups, group_topk)
        probs = (
            scores / (scores.sum(dim=-1, keepdim=True) + 1e-20) if topk > 1 else scores
        )
    else:
        raise ValueError(f"Invalid score_function: {score_function}")

    if scaling_factor:
        probs = probs * scaling_factor

    probs = probs.type_as(logits)

    # TODO Try using element-wise operations instead of scatter?
    topk_masked_gates = torch.zeros_like(logits).scatter(1, top_indices, probs)
    topk_map = torch.zeros_like(logits).int().scatter(1, top_indices, 1).bool()
    return RoutingResult(
        probs=topk_masked_gates,
        routing_map=topk_map,
        expert_indices=top_indices.sort(dim=-1).values,
    )


def ensure_divisibility(numerator, denominator):
    """Ensure that numerator is divisible by the denominator."""
    assert numerator % denominator == 0, "{} is not divisible by {}".format(
        numerator, denominator
    )


def divide(numerator, denominator):
    """Ensure that numerator is divisible by the denominator and return
    the division value."""
    ensure_divisibility(numerator, denominator)
    return numerator // denominator
